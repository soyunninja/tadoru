test('runResetPassword refuses when not run as root', async () => {
  const { options, calls } = baseOptions({ isRoot: false });
  const result = await runResetPassword(options);
  assert.equal(result.ok, false);
  if (!result.ok) {
    assert.match(result.error, /root/i);
    assert.match(result.error, /sudo/i);
  }
  assert.equal(calls.length, 0);
});

test('runResetPassword refuses when the env file does not exist, and points at install-service', async () => {
  const { options, calls } = baseOptions({ pathExists: () => false });
  const result = await runResetPassword(options);
  assert.equal(result.ok, false);
  if (!result.ok) {
    assert.match(result.error, /does not exist/i);
    assert.match(result.error, /install-service/);
  }
  assert.ok(!calls.some((c) => c.port === 'writeEnvFile'));
  assert.ok(!calls.some((c) => c.port === 'backupEnvFile'));
});


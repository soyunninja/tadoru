// No spawn/exec-style port exists for this command at all — by construction,
// the generated password can never be passed across a shell/process boundary.
// ---------------------------------------------------------------------------

test('resetPassword.ts defines no spawn/exec-style port that could receive the password', () => {
  const sourcePath = fileURLToPath(new URL('./resetPassword.ts', import.meta.url));
  const source = readFileSync(sourcePath, 'utf8');
  assert.doesNotMatch(source, /execFileSync|execSync|spawnSync|spawn\(|child_process/);
});

// ---------------------------------------------------------------------------
// Real port implementations, wired end to end against a temp file.
// ---------------------------------------------------------------------------

test('runResetPassword, wired to the real ports, rewrites a real env file and keeps it at mode 0600', async () => {
  await withTempDirAsync(async (dir) => {
    {
      const envPath = join(dir, 'tadoru.env');
      writeFileSync(
        envPath,
        '# operator comment\nTADORU_ADMIN_PASSWORD_HASH=oldhash\nTADORU_ADMIN_PASSWORD_SALT=oldsalt\nTADORU_SITES=example.com\n',
        { mode: 0o600 },
      );

      const { existsSync, readFileSync: realReadFileSync, copyFileSync } = await import('node:fs');
      const result = await runResetPassword({
        isRoot: true,
        dryRun: false,
        envFilePath: envPath,
        log: () => {},
        randomBytes: (size: number) => new Uint8Array(size).fill(3),
        pathExists: existsSync,
        readEnvFile: (p: string) => realReadFileSync(p, 'utf8'),
        backupEnvFile: (source: string, backup: string) => copyFileSync(source, backup),
        writeEnvFile: writeEnvFileToDisk,
        now: () => new Date('2026-09-09T10:20:30.000Z'),
      });

      assert.equal(result.ok, true);
      const mode = statSync(envPath).mode & 0o777;
      assert.equal(mode, 0o600);

      const rewritten = readFileSync(envPath, 'utf8');
      assert.match(rewritten, /^# operator comment$/m);
      assert.match(rewritten, /^TADORU_SITES=example\.com$/m);
      assert.doesNotMatch(rewritten, /oldhash|oldsalt/);

      const backupPath = join(dir, 'tadoru.env.bak-2026-09-09T10-20-30');
      assert.ok(existsSync(backupPath), 'a dated backup must exist');
      assert.match(readFileSync(backupPath, 'utf8'), /oldhash/);
    }
  });
});

test('runResetPassword, wired to the real ports, produces a hash+salt pair that verifies against the printed password', async () => {
  await withTempDirAsync(async (dir) => {
    {
      const envPath = join(dir, 'tadoru.env');
      writeFileSync(envPath, 'TADORU_ADMIN_PASSWORD_HASH=oldhash\nTADORU_ADMIN_PASSWORD_SALT=oldsalt\n', { mode: 0o600 });

      const { existsSync, readFileSync: realReadFileSync, copyFileSync } = await import('node:fs');
      const logs: string[] = [];
      const result = await runResetPassword({
        isRoot: true,
        dryRun: false,
        envFilePath: envPath,
        log: (m: string) => logs.push(m),
        pathExists: existsSync,
        readEnvFile: (p: string) => realReadFileSync(p, 'utf8'),
        backupEnvFile: (source: string, backup: string) => copyFileSync(source, backup),
        writeEnvFile: writeEnvFileToDisk,
      });
      assert.equal(result.ok, true);

      const printedPassword = /New admin password: (\S+)/.exec(logs.join('\n'))?.[1] as string;
      const content = readFileSync(envPath, 'utf8');
      const hash = /^TADORU_ADMIN_PASSWORD_HASH=([0-9a-f]+)$/m.exec(content)?.[1] as string;
      const salt = /^TADORU_ADMIN_PASSWORD_SALT=([0-9a-f]+)$/m.exec(content)?.[1] as string;
      assert.equal(verifyPasswordHash(printedPassword, { hash, salt }), true);
    }
  });
});

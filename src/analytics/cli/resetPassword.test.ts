test('runResetPassword --dry-run performs no filesystem effect', async () => {
  const { options, logs, calls } = baseOptions({ dryRun: true });
  const result = await runResetPassword(options);
  assert.equal(result.ok, true);
  assert.ok(!calls.some((c) => c.port === 'writeEnvFile'));
  assert.ok(!calls.some((c) => c.port === 'backupEnvFile'));
  assert.ok(!calls.some((c) => c.port === 'readEnvFile'));
  assert.match(logs.join('\n'), /dry-run/i);
});

test('runResetPassword --dry-run still refuses when not root', async () => {
  const { options, calls } = baseOptions({ dryRun: true, isRoot: false });
  const result = await runResetPassword(options);
  assert.equal(result.ok, false);
  assert.equal(calls.length, 0);
});

test('runResetPassword --dry-run still refuses when the env file is missing', async () => {
  const { options, calls } = baseOptions({ dryRun: true, pathExists: () => false });
  const result = await runResetPassword(options);
  assert.equal(result.ok, false);
  assert.ok(!calls.some((c) => c.port === 'writeEnvFile'));
});


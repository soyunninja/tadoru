test('runResetPassword preserves unrelated lines and comments, only touching credential lines', async () => {
  const { options, calls } = baseOptions();
  const result = await runResetPassword(options);
  assert.equal(result.ok, true);

  const writeCall = calls.find((c) => c.port === 'writeEnvFile');
  assert.ok(writeCall);
  const content = writeCall.args[1] as string;
  assert.match(content, /^# a comment$/m);
  assert.match(content, /^TADORU_SITES=example\.com$/m);
  assert.doesNotMatch(content, /oldhash|oldsalt/);
});

test('runResetPassword backs up the existing env file before rewriting it', async () => {
  const { options, calls } = baseOptions();
  const result = await runResetPassword(options);
  assert.equal(result.ok, true);

  const backupIndex = calls.findIndex((c) => c.port === 'backupEnvFile');
  const writeIndex = calls.findIndex((c) => c.port === 'writeEnvFile');
  assert.ok(backupIndex !== -1, 'backupEnvFile must be called');
  assert.ok(backupIndex < writeIndex, 'the backup must happen before the file is rewritten');

  const backupCall = calls[backupIndex];
  assert.equal(backupCall?.args[0], options.envFilePath);
  assert.match(backupCall?.args[1] as string, /tadoru\.env\.bak-/);
});

test('runResetPassword prints the new password to stdout exactly once, with a restart reminder, and never passes it to writeEnvFile/backupEnvFile as an argument', async () => {
  const { options, logs, calls } = baseOptions();
  const result = await runResetPassword(options);
  assert.equal(result.ok, true);

  const output = logs.join('\n');
  const matches = [...output.matchAll(/New admin password: (\S+)/g)];
  assert.equal(matches.length, 1, 'the password must be printed exactly once');
  const password = matches[0]?.[1] as string;
  assert.ok(password.length > 0);
  assert.match(output, /will not be shown again/i);
  assert.match(output, /sudo systemctl restart tadoru/);

  for (const call of calls) {
    if (call.port === 'writeEnvFile') continue; // the hash+salt derived from it legitimately live in the content
    for (const arg of call.args) {
      assert.ok(typeof arg !== 'string' || !arg.includes(password), `password leaked into a ${call.port} argument`);
    }
  }
  // Even writeEnvFile's content must carry the derived hash, never the plaintext password itself.
  const writeCall = calls.find((c) => c.port === 'writeEnvFile');
  assert.ok(writeCall && !(writeCall.args[1] as string).includes(password));
});

test('runResetPassword exits with a non-ok Result on every refusal (root, missing file)', async () => {
  const notRoot = await runResetPassword(baseOptions({ isRoot: false }).options);
  const missingFile = await runResetPassword(baseOptions({ pathExists: () => false }).options);
  assert.equal(notRoot.ok, false);
  assert.equal(missingFile.ok, false);
});


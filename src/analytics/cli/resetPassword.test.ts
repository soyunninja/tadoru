test('rewriteCredentialLines replaces existing hash/salt lines in place, preserving everything else', () => {
  const content = [
    '# Generated by `tadoru install-service`. Keep this file at mode 0600.',
    'TADORU_ADMIN_PASSWORD_HASH=oldhash',
    'TADORU_ADMIN_PASSWORD_SALT=oldsalt',
    'TADORU_SITES=example.com',
    'TADORU_HOST=127.0.0.1',
    '',
  ].join('\n');

  const rewritten = rewriteCredentialLines(content, 'newhash', 'newsalt');
  const lines = rewritten.split('\n');

  assert.deepEqual(lines, [
    '# Generated by `tadoru install-service`. Keep this file at mode 0600.',
    'TADORU_ADMIN_PASSWORD_HASH=newhash',
    'TADORU_ADMIN_PASSWORD_SALT=newsalt',
    'TADORU_SITES=example.com',
    'TADORU_HOST=127.0.0.1',
    '',
  ]);
});

test('rewriteCredentialLines removes an old plaintext TADORU_ADMIN_PASSWORD line and replaces it with hash+salt', () => {
  const content = [
    '# a hand-written comment an operator added',
    'TADORU_ADMIN_PASSWORD=old-plaintext-value',
    '',
    'TADORU_SITES=example.com',
  ].join('\n');

  const rewritten = rewriteCredentialLines(content, 'newhash', 'newsalt');

  assert.doesNotMatch(rewritten, /^TADORU_ADMIN_PASSWORD=/m);
  assert.match(rewritten, /^TADORU_ADMIN_PASSWORD_HASH=newhash$/m);
  assert.match(rewritten, /^TADORU_ADMIN_PASSWORD_SALT=newsalt$/m);
  // Unrelated lines, including the blank line and the operator's own comment, survive verbatim.
  assert.match(rewritten, /^# a hand-written comment an operator added$/m);
  assert.match(rewritten, /^TADORU_SITES=example\.com$/m);
});

test('rewriteCredentialLines leaves exactly one credential pair when plaintext precedes hash and salt lines', () => {
  // An env file part-way through the migration: the old plaintext line is still
  // there, above the hash+salt pair a later `install-service` run appended. The
  // plaintext line is the one replaced in place, so the real hash and salt lines
  // further down must be dropped rather than emitted a second time.
  const content = [
    'TADORU_ADMIN_PASSWORD=old-plaintext-value',
    'TADORU_SITES=example.com',
    'TADORU_ADMIN_PASSWORD_HASH=oldhash',
    'TADORU_ADMIN_PASSWORD_SALT=oldsalt',
  ].join('\n');

  const rewritten = rewriteCredentialLines(content, 'newhash', 'newsalt');

  const hashLines = rewritten.split('\n').filter((line) => line.startsWith('TADORU_ADMIN_PASSWORD_HASH='));
  const saltLines = rewritten.split('\n').filter((line) => line.startsWith('TADORU_ADMIN_PASSWORD_SALT='));
  assert.deepEqual(hashLines, ['TADORU_ADMIN_PASSWORD_HASH=newhash']);
  assert.deepEqual(saltLines, ['TADORU_ADMIN_PASSWORD_SALT=newsalt']);
  assert.doesNotMatch(rewritten, /^TADORU_ADMIN_PASSWORD=/m);
  assert.match(rewritten, /^TADORU_SITES=example\.com$/m);
});

test('rewriteCredentialLines appends hash+salt when no credential line exists at all', () => {
  const content = 'TADORU_SITES=example.com\n';
  const rewritten = rewriteCredentialLines(content, 'newhash', 'newsalt');
  assert.match(rewritten, /^TADORU_SITES=example\.com$/m);
  assert.match(rewritten, /^TADORU_ADMIN_PASSWORD_HASH=newhash$/m);
  assert.match(rewritten, /^TADORU_ADMIN_PASSWORD_SALT=newsalt$/m);
});


import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  envBackupFileName,
  resolveEnvBackupPath,
  rewriteCredentialLines,
  runResetPassword,
  writeEnvFileToDisk,
} from './resetPassword.ts';
import type { RunResetPasswordOptions } from './resetPassword.ts';
import { verifyPasswordHash } from '../infrastructure/http/adminAuth.ts';

async function withTempDirAsync<T>(fn: (dir: string) => Promise<T>): Promise<T> {
  const dir = mkdtempSync(join(tmpdir(), 'tadoru-reset-password-test-'));
  try {
    return await fn(dir);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

function baseOptions(overrides: Partial<RunResetPasswordOptions> = {}) {
  const logs: string[] = [];
  const calls: { readonly port: string; readonly args: readonly unknown[] }[] = [];

  const options: RunResetPasswordOptions = {
    isRoot: true,
    dryRun: false,
    envFilePath: '/etc/tadoru/tadoru.env',
    log: (message: string) => logs.push(message),
    randomBytes: (size: number) => new Uint8Array(size).fill(9),
    pathExists: (path: string) => {
      calls.push({ port: 'pathExists', args: [path] });
      return true;
    },
    readEnvFile: (path: string) => {
      calls.push({ port: 'readEnvFile', args: [path] });
      return '# a comment\nTADORU_ADMIN_PASSWORD_HASH=oldhash\nTADORU_ADMIN_PASSWORD_SALT=oldsalt\nTADORU_SITES=example.com\n';
    },
    backupEnvFile: (source: string, backup: string) => {
      calls.push({ port: 'backupEnvFile', args: [source, backup] });
    },
    writeEnvFile: (path: string, content: string) => {
      calls.push({ port: 'writeEnvFile', args: [path, content] });
    },
    now: () => new Date('2026-09-09T10:20:30.000Z'),
    ...overrides,
  };

  return { options, logs, calls };
}

